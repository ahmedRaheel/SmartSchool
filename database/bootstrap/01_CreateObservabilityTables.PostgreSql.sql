-- SmartSchool PostgreSQL observability bootstrap
-- Idempotent. Safe to run repeatedly after the application database exists.

BEGIN;

CREATE SCHEMA IF NOT EXISTS observability;

CREATE TABLE IF NOT EXISTS observability.application_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp_utc timestamptz NOT NULL DEFAULT now(),
    level varchar(32) NOT NULL,
    service varchar(128) NULL,
    message text NOT NULL,
    message_template text NULL,
    exception text NULL,
    trace_id varchar(64) NULL,
    correlation_id varchar(128) NULL,
    request_path varchar(1024) NULL,
    properties jsonb NULL
);

-- Upgrade older installations without dropping data.
ALTER TABLE observability.application_log
    ADD COLUMN IF NOT EXISTS timestamp_utc timestamptz NOT NULL DEFAULT now(),
    ADD COLUMN IF NOT EXISTS level varchar(32),
    ADD COLUMN IF NOT EXISTS service varchar(128),
    ADD COLUMN IF NOT EXISTS message text,
    ADD COLUMN IF NOT EXISTS message_template text,
    ADD COLUMN IF NOT EXISTS exception text,
    ADD COLUMN IF NOT EXISTS trace_id varchar(64),
    ADD COLUMN IF NOT EXISTS correlation_id varchar(128),
    ADD COLUMN IF NOT EXISTS request_path varchar(1024),
    ADD COLUMN IF NOT EXISTS properties jsonb;

CREATE INDEX IF NOT EXISTS ix_application_log_timestamp_utc
    ON observability.application_log (timestamp_utc DESC);

CREATE INDEX IF NOT EXISTS ix_application_log_level_timestamp
    ON observability.application_log (level, timestamp_utc DESC);

CREATE INDEX IF NOT EXISTS ix_application_log_trace_id
    ON observability.application_log (trace_id);

CREATE INDEX IF NOT EXISTS ix_application_log_correlation_id
    ON observability.application_log (correlation_id);

CREATE INDEX IF NOT EXISTS ix_application_log_service_timestamp
    ON observability.application_log (service, timestamp_utc DESC);

COMMIT;

-- Verification
SELECT
    to_regclass('observability.application_log') AS application_log_table,
    COUNT(*) AS current_log_rows
FROM observability.application_log;
