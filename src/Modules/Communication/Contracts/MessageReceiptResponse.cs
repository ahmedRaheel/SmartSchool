namespace SmartSchool.Modules.Communication.Contracts;

public sealed record MessageReceiptResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static MessageReceiptResponse FromEntity(
        Models.MessageReceipt entity)
    {
        return new MessageReceiptResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
