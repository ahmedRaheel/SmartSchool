namespace SmartSchool.Modules.Identity.Contracts;

public sealed record UserProfileResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static UserProfileResponse FromEntity(
        Models.UserProfile entity)
    {
        return new UserProfileResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
