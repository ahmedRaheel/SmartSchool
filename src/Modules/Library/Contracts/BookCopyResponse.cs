namespace SmartSchool.Modules.Library.Contracts;

public sealed record BookCopyResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static BookCopyResponse FromEntity(
        Models.BookCopy entity)
    {
        return new BookCopyResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
