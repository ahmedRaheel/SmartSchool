namespace SmartSchool.Modules.Finance.Contracts;

public sealed record StudentFeeResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static StudentFeeResponse FromEntity(
        Models.StudentFee entity)
    {
        return new StudentFeeResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
