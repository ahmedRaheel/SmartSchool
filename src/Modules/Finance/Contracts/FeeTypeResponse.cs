namespace SmartSchool.Modules.Finance.Contracts;

public sealed record FeeTypeResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static FeeTypeResponse FromEntity(
        Models.FeeType entity)
    {
        return new FeeTypeResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
