namespace SmartSchool.Modules.Tenancy.Contracts;

public sealed record SubscriptionResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static SubscriptionResponse FromEntity(
        Models.Subscription entity)
    {
        return new SubscriptionResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
