namespace SmartSchool.Modules.Workflow.Contracts;

public sealed record ApprovalResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static ApprovalResponse FromEntity(
        Models.Approval entity)
    {
        return new ApprovalResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
