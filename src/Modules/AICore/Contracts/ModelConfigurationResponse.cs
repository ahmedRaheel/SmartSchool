namespace SmartSchool.Modules.AICore.Contracts;

public sealed record ModelConfigurationResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static ModelConfigurationResponse FromEntity(
        Models.ModelConfiguration entity)
    {
        return new ModelConfigurationResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
