namespace SmartSchool.Modules.Students.Contracts;

public sealed record EnrollmentResponse(
    Guid Id,
    string Code,
    string Name,
    bool IsActive,
    string? MetadataJson,
    DateTimeOffset CreatedAt,
    DateTimeOffset? UpdatedAt)
{
    public static EnrollmentResponse FromEntity(
        Models.Enrollment entity)
    {
        return new EnrollmentResponse(
            entity.Id,
            entity.Code,
            entity.Name,
            entity.IsActive,
            entity.MetadataJson,
            entity.CreatedAt,
            entity.UpdatedAt);
    }
}
